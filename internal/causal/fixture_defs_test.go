var fixtureOrigin = time.Date(2026, time.October, 27, 12, 0, 0, 0, time.UTC)

func fxTime(offset time.Duration) time.Time { return fixtureOrigin.Add(offset) }

const fxMemoryTotal = uint64(16 << 30)

func fxIncident(name string, span, triggerAt time.Duration, triggerType string) *incident.Incident {
	sum := sha256.Sum256([]byte(name))
	end := fxTime(span)
	return &incident.Incident{
		SchemaVersion: incident.SchemaVersion,
		ID:            "inc_" + hex.EncodeToString(sum[:16]),
		CreatedAt:     end,
		TriggeredAt:   fxTime(triggerAt),
		CaptureStart:  fxTime(0),
		CaptureEnd:    end,
		Window:        incident.CaptureWindow{PreTrigger: triggerAt, PostTrigger: span - triggerAt},
		Trigger:       incident.Trigger{Type: triggerType},
		Metadata: incident.Metadata{
			AgentVersion: incident.AgentVersion,
			Host:         incident.HostMetadata{OS: "linux", Architecture: "arm64", CPUCount: 4, MemoryTotal: fxMemoryTotal},
		},
		Privacy: incident.PrivacyReport{Policy: "conservative"},
	}
}

// fxSystem builds a host section. A negative diskFreePercent marks disk
// telemetry as unavailable (no fabricated zero-free-space reading).
func fxSystem(memoryUsedPercent, diskFreePercent float64) *collector.SystemSnapshot {
	sys := &collector.SystemSnapshot{
		LoadAvailable: true, CPUAvailable: true, CPUPercentAvailable: true,
		MemoryStatsAvailable: true, ProcessCountAvailable: true,
		MemoryTotal: fxMemoryTotal,
		MemoryUsed:  uint64(float64(fxMemoryTotal) * memoryUsedPercent / 100),
		CPUCount:    4, CPUPercent: 10,
	}
	if diskFreePercent >= 0 {
		const diskTotal = uint64(1 << 40)
		sys.DiskStatsAvailable = true
		sys.DiskTotal = diskTotal
		sys.DiskFree = uint64(float64(diskTotal) * diskFreePercent / 100)
		sys.DiskFilesystem = "/var/lib/docker"
	}
	return sys
}

func fxSnapshots(count int, step time.Duration, gen func(index int) collector.Snapshot) []collector.Snapshot {
	out := make([]collector.Snapshot, count)
	for index := 0; index < count; index++ {
		out[index] = gen(index)
		out[index].Timestamp = fxTime(time.Duration(index) * step)
	}
	return out
}

func fxProcess(pid, ppid, pgid int, startTicks int64, state string, cpuPercent float64) collector.ProcessSnapshot {
	return collector.ProcessSnapshot{
		Process:    platform.Process{PID: pid, PPID: ppid, PGID: pgid, SID: pgid, Name: "worker", State: state, StartTicks: startTicks},
		CPUPercent: cpuPercent,
		OpenFDs:    -1,
	}
}

func fxConnection(inode uint64, state string, pid int) *collector.ConnectionSnapshot {
	return &collector.ConnectionSnapshot{
		LocalAddr: "127.0.0.1", LocalPort: 40001,
		RemoteAddr: "203.0.113.10", RemotePort: 443,
		State: state, Inode: inode, PID: pid, FD: 7,
	}
}

func fxProcessMetadata(pid, ppid, pgid int, startTicks int64) incident.ProcessMetadata {
	return incident.ProcessMetadata{PID: pid, PPID: ppid, PGID: pgid, SID: pgid, StartTicks: startTicks, Name: "worker"}
}

type causalFixture struct {
	Name  string
	Class string // "GOLDEN" | "HEALTHY"
	// gate names the audit finding whose engine fix the fixture depends on.
	// gated fixtures are skipped unless DEPREHENDO_REVIEW_AUDIT=1 (the principal-audit
	// test convention): they encode the reviewed post-fix contract and fail
	// on the code as audited, so they may not run in the default suite.
	Gate string
	// mode "events" loads a hand-authored normalized event stream
	// (events.json) instead of a bundle (incident.json), for findings whose
	// inputs need telemetry v1 bundles cannot carry (kernel OOM records).
	// such fixtures still inject only rule-declared, V3-validated edges.
	Mode string // "" = bundle incident, "events" = normalized event stream
	// forbidden lists event types that must not appear for this input even
	// though the global unobservable set is always forbidden.
	Forbidden []string
	// allows relaxes the global unobservable guard for named event types
	// only: used deliberately by events-mode fixtures whose scenario
	// requires a kernel OOM record (see the A6/A8 fixture notes).
	Allows []string
	Notes  []string
	Build  func(t *testing.T) *incident.Incident // nil for events-mode
}

