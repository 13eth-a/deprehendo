package causal

// fixture comparison (4.35/4.36/4.40): the fixture expectations are reviewed
// data, so the failures here name the exact structural difference (a missing
// edge, an extra CAUSES claim, a changed root role) rather than rendering text.

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

type expectedEvent struct {
	Type         string `json:"type"`
	Count        int    `json:"count"`
	OnsetUnknown *bool  `json:"onset_unknown,omitempty"`
}

type expectedEdge struct {
	FromType   string `json:"from_type"`
	ToType     string `json:"to_type"`
	Relation   string `json:"relation"`
	Rule       string `json:"rule"`
	Confidence string `json:"confidence"`
	// ExplainMentions (A5): every listed fragment must appear in explain-edge
	// output for this edge, so a declared contradiction check cannot vanish
	// from the explanation without failing the fixture.
	ExplainMentions []string `json:"explain_must_mention,omitempty"`
}

// expectedSignatureBan (A11) asserts what a phase 3 signature's linked
// evidence may not include. types listed must exist on the timeline, so a
// banned linkage cannot pass vacuously.
type expectedSignatureBan struct {
	Signature string   `json:"signature"`
	Types     []string `json:"types"`
}

type expectedRoot struct {
	Type         string `json:"type"`
	Kind         string `json:"kind"`
	Role         string `json:"role"`
	Confidence   string `json:"confidence"`
	OnsetUnknown bool   `json:"onset_unknown"`
}

// expectedFailure mirrors one FailureAnalysis (§5.2): every anchor gets one,
// so AMBIGUOUS/UNKNOWN anchors are compared too (A15).
type expectedFailure struct {
	AnchorType      string         `json:"anchor_type"`
	Status          string         `json:"status"`
	Candidates      []expectedRoot `json:"candidates"`
	ChainTypes      []string       `json:"chain_types,omitempty"`
	MissingIncludes []string       `json:"missing_evidence_includes,omitempty"`
	Alternatives    []string       `json:"alternatives,omitempty"`
}

type causalExpectation struct {
	Name            string                 `json:"name"`
	Class           string                 `json:"class"` // GOLDEN | HEALTHY
	Notes           []string               `json:"notes"`
	Events          []expectedEvent        `json:"events"`
	ForbiddenEvents []string               `json:"forbidden_events,omitempty"`
	Edges           []expectedEdge         `json:"edges"`
	Failures        []expectedFailure      `json:"failures"`
	SignatureBans   []expectedSignatureBan `json:"signature_bans,omitempty"`
	GraphHealthy    bool                   `json:"graph_healthy"`
}

func boolPtr(v bool) *bool { return &v }

// buildExpectation derives the reviewed shape from an actual analysis so the
// generator can print a draft. committed expectations are edited and reviewed,
// never regenerated by the test suite.
func buildExpectation(name, class string, notes, forbidden []string, tl *Timeline, g *Graph) causalExpectation {
	sort.SliceStable(g.FailureAnalyses(), func(i, j int) bool {
		return g.Get(g.FailureAnalyses()[i].Anchor).Timestamp.Before(g.Get(g.FailureAnalyses()[j].Anchor).Timestamp)
	})
	counts := map[EventType]int{}
	onset := map[EventType]bool{}
	onsetmixed := map[EventType]bool{}
	for _, event := range tl.Events {
		counts[event.Type]++
		if _, seen := onset[event.Type]; seen {
			if onset[event.Type] != event.OnsetUnknown {
				onsetmixed[event.Type] = true
			}
			continue
		}
		onset[event.Type] = event.OnsetUnknown
	}
	var eventTypes []string
	for eventType := range counts {
		eventTypes = append(eventTypes, string(eventType))
	}
	sort.Strings(eventTypes)
	expected := causalExpectation{
		Name: name, Class: class, Notes: notes, ForbiddenEvents: forbidden,
		Failures:     []expectedFailure{},
		GraphHealthy: g.Healthy(),
		Edges:        []expectedEdge{}, Events: []expectedEvent{},
	}
	for _, eventType := range eventTypes {
		entry := expectedEvent{Type: eventType, Count: counts[EventType(eventType)]}
		if !onsetmixed[EventType(eventType)] {
			entry.OnsetUnknown = boolPtr(onset[EventType(eventType)])
		}
		expected.Events = append(expected.Events, entry)
	}
	for _, edge := range g.Edges {
		expected.Edges = append(expected.Edges, expectedEdge{
			FromType: string(g.Get(edge.From).Type), ToType: string(g.Get(edge.To).Type),
			Relation: string(edge.Relation), Rule: edge.RuleID, Confidence: string(edge.Confidence),
		})
	}
	sort.SliceStable(expected.Edges, func(i, j int) bool {
		a, b := expected.Edges[i], expected.Edges[j]
		if a.FromType != b.FromType {
			return a.FromType < b.FromType
		}
		if a.ToType != b.ToType {
			return a.ToType < b.ToType
		}
		return a.Rule < b.Rule
	})
	for _, analysis := range g.FailureAnalyses() {
		entry := expectedFailure{
			AnchorType: string(analysis.AnchorType),
			Status:     string(analysis.Status),
			Candidates: []expectedRoot{},
		}
		for _, id := range analysis.KnownChain {
			entry.ChainTypes = append(entry.ChainTypes, string(g.Get(id).Type))
		}
		for _, candidate := range analysis.Candidates {
			entry.Candidates = append(entry.Candidates, expectedRoot{
				Type:         string(g.Get(candidate.Event).Type),
				Kind:         string(candidate.Kind),
				Role:         string(candidate.Role),
				Confidence:   string(candidate.Confidence),
				OnsetUnknown: candidate.OnsetUnknown,
			})
		}
		for _, missing := range analysis.MissingEvidence {
			if containsFragment(entry.MissingIncludes, missing) {
				continue
			}
			entry.MissingIncludes = append(entry.MissingIncludes, missing)
		}
		entry.Alternatives = analysis.Alternatives
		expected.Failures = append(expected.Failures, entry)
	}
	return expected
}

func containsFragment(values []string, query string) bool {
	for _, v := range values {
		if strings.Contains(v, query) {
			return true
		}
	}
	return false
}

type edgeKey struct{ From, To, Relation, Rule, Confidence string }
type failureKey struct{ AnchorType, Status string }

func equalStrings(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}

// TestCausalFixtures is the fixture suite (4.35/4.36). it asserts the exact
// event multiset, the exact rule-backed edge multiset, exact root roles, and
// the honest unknown-cause anchor, so a false causal claim fails the build.
func TestCausalFixtures(t *testing.T) {
	seen := map[string]bool{}
	for _, fixture := range causalFixtures() {
		fixture := fixture
		seen[fixture.Name] = true
		t.Run(fixture.Name, func(t *testing.T) {
			if fixture.Gate != "" && os.Getenv("RUNOPSY_REVIEW_AUDIT") == "" {
				t.Skipf("gated fixture pending %s (set RUNOPSY_REVIEW_AUDIT=1 to run)", fixture.Gate)
			}
			var timeline *Timeline
			var graph *Graph
			switch fixture.Mode {
			case "", "bundle":
				inc := loadCausalFixture(t, fixture.Name)
				timeline = BuildTimeline(inc)
				graph = NewGraph(timeline)
				if _, err := NewEngine(Rules(), timeline.Origin).Apply(graph, nil); err != nil {
					t.Fatalf("apply rules: %v", err)
				}
			case "events":
				timeline, graph = loadEventsFixtureDec(t, fixture.Name).timeline(t)
			default:
				t.Fatalf("unknown fixture mode %q", fixture.Mode)
			}
			expected := loadFixtureExpectation(t, fixture.Name)
			if expected.Class != fixture.Class {
				t.Fatalf("expectation class = %q, definition class = %q", expected.Class, fixture.Class)
			}
			if err := graph.Validate(); err != nil {
				t.Fatalf("graph failed structural validation: %v", err)
			}
			for _, violation := range compareExpectation(expected, timeline, graph) {
				t.Error(violation)
			}
			// A healthy fixture must also be healthy by the definition used by
			// reports: no failure anchors and no causal claims (episode
			// reconstruction edges are history, not claims, §5.5).
			if expected.Class == "HEALTHY" {
				for _, edge := range graph.Edges {
					if isCausal(edge.Relation) {
						t.Errorf("healthy fixture produced a causal claim edge %s", edge.RuleID)
					}
				}
				if len(graph.FailureAnalyses()) != 0 || !graph.Healthy() {
					t.Errorf("healthy fixture reports failure anchors: %+v", graph.FailureAnalyses())
				}
			}
			allowed := map[EventType]bool{}
			for _, name := range fixture.Allows {
				allowed[EventType(name)] = true
			}
			for _, eventType := range unobservableEventTypes {
				if allowed[eventType] {
					continue
				}
				if countEvents(timeline, eventType) != 0 {
					t.Errorf("v1 bundle fabricated unobservable event %s", eventType)
				}
			}
		})
	}
	// directories without a definition are unreviewed fixtures and must not
	// silently rot in the repository.
	entries, err := os.ReadDir(filepath.Join("..", "..", "testdata", "causal"))
	if err != nil {
		t.Fatalf("read fixture root: %v", err)
	}
	for _, entry := range entries {
		if entry.IsDir() && !seen[entry.Name()] {
			t.Errorf("testdata/causal/%s has no fixture definition", entry.Name())
		}
	}
}

func countEvents(tl *Timeline, eventType EventType) int {
	count := 0
	for _, event := range tl.Events {
		if event.Type == eventType {
			count++
		}
	}
	return count
}

func compareExpectation(expected causalExpectation, tl *Timeline, g *Graph) []string {
	var problems []string
	actualcounts := map[EventType]int{}
	actualonset := map[EventType]map[bool]bool{}
	for _, event := range tl.Events {
		actualcounts[event.Type]++
		if actualonset[event.Type] == nil {
			actualonset[event.Type] = map[bool]bool{}
		}
		actualonset[event.Type][event.OnsetUnknown] = true
	}
	expectedcounts := map[EventType]int{}
	for _, event := range expected.Events {
		expectedcounts[EventType(event.Type)] += event.Count
	}
	for eventType, want := range expectedcounts {
		if got := actualcounts[eventType]; got != want {
			problems = append(problems, fmt.Sprintf("event %s count = %d, want %d", eventType, got, want))
		}
	}
	for eventType, got := range actualcounts {
		if expectedcounts[eventType] == 0 {
			problems = append(problems, fmt.Sprintf("unexpected event %s (count %d)", eventType, got))
		}
	}
	for _, event := range expected.Events {
		if event.OnsetUnknown == nil {
			continue
		}
		for unknown := range actualonset[EventType(event.Type)] {
			if unknown != *event.OnsetUnknown {
				problems = append(problems, fmt.Sprintf("event %s onset_unknown = %v, want %v",
					event.Type, unknown, *event.OnsetUnknown))
				break
			}
		}
	}
	forbidden := map[EventType]bool{}
	for _, name := range expected.ForbiddenEvents {
		forbidden[EventType(name)] = true
	}
	for eventType := range forbidden {
		if actualcounts[eventType] > 0 {
			problems = append(problems, fmt.Sprintf("forbidden event %s was emitted", eventType))
		}
	}

	actualedges := map[edgeKey]int{}
	for _, edge := range g.Edges {
		actualedges[edgeKey{
			From: string(g.Get(edge.From).Type), To: string(g.Get(edge.To).Type),
			Relation: string(edge.Relation), Rule: edge.RuleID, Confidence: string(edge.Confidence),
		}]++
	}
	wantedges := map[edgeKey]int{}
	for _, edge := range expected.Edges {
		wantedges[edgeKey{From: edge.FromType, To: edge.ToType, Relation: edge.Relation,
			Rule: edge.Rule, Confidence: edge.Confidence}]++
	}
	problems = append(problems, compareCounts("edge", actualedges, wantedges)...)

	// A5: explain-edge must name the declared contradiction checks listed in
	// the expectation. the walk is by graph edge index, so explain() calls
	// the exact edge the expectation row describes.
	for index := range g.Edges {
		edge := g.Edges[index]
		key := edgeKey{
			From: string(g.Get(edge.From).Type), To: string(g.Get(edge.To).Type),
			Relation: string(edge.Relation), Rule: edge.RuleID, Confidence: string(edge.Confidence),
		}
		for _, want := range expected.Edges {
			if len(want.ExplainMentions) == 0 {
				continue
			}
			wantkey := edgeKey{From: want.FromType, To: want.ToType, Relation: want.Relation,
				Rule: want.Rule, Confidence: want.Confidence}
			if wantkey != key {
				continue
			}
			text, err := g.Explain(index)
			if err != nil {
				problems = append(problems, fmt.Sprintf("edge %s: explain-edge failed: %v", key.Rule, err))
				continue
			}
			for _, fragment := range want.ExplainMentions {
				if !strings.Contains(text, fragment) {
					problems = append(problems, fmt.Sprintf("edge %s explanation does not mention %q:\n%s", key.Rule, fragment, text))
				}
			} // the blanked whole-text "none recorded" scan is gone: the fixed
			// engine's honest alternatives line ("none recorded by the engine
			// (checked, empty)") contains that phrase on every edge. the
			// ExplainMentions fragments above pin the A5 regression: declared
			// checks must be reported with their evaluated status.
			break
		}
	}

	// A11: a signature's linked evidence may not claim the banned types, and
	// the banned types must exist on the timeline so the ban is not vacuous.
	for _, ban := range expected.SignatureBans {
		for _, name := range ban.Types {
			if countEvents(tl, EventType(name)) == 0 {
				problems = append(problems, fmt.Sprintf("vacuous signature ban: %s is not on the timeline", name))
			}
		}
		linked := map[EventType]bool{}
		for _, id := range RelatedEventIDs(tl, ban.Signature, nil) {
			for _, event := range tl.Events {
				if event.ID == id {
					linked[event.Type] = true
					break
				}
			}
		}
		for _, banned := range ban.Types {
			if linked[EventType(banned)] {
				problems = append(problems, fmt.Sprintf("signature %s links %s as related evidence", ban.Signature, banned))
			}
		}
	}

	actualfailures := map[failureKey]int{}
	for _, analysis := range g.FailureAnalyses() {
		actualfailures[failureKey{AnchorType: string(analysis.AnchorType), Status: string(analysis.Status)}]++
	}
	wantfailures := map[failureKey]int{}
	for _, failure := range expected.Failures {
		wantfailures[failureKey{AnchorType: failure.AnchorType, Status: failure.Status}]++
		// Per-anchor structural comparisons beyond the multiset.
		var match *FailureAnalysis
		for i := range g.FailureAnalyses() {
			if string(g.FailureAnalyses()[i].AnchorType) == failure.AnchorType &&
				string(g.FailureAnalyses()[i].Status) == failure.Status {
				match = &g.FailureAnalyses()[i]
				break
			}
		}
		if match == nil {
			continue
		}
		if len(match.Candidates) != len(failure.Candidates) {
			problems = append(problems, fmt.Sprintf("anchor %s candidate count = %d, want %d",
				failure.AnchorType, len(match.Candidates), len(failure.Candidates)))
		} else {
			for i, root := range failure.Candidates {
				got := match.Candidates[i]
				if string(g.Get(got.Event).Type) != root.Type || string(got.Kind) != root.Kind ||
					string(got.Role) != root.Role || string(got.Confidence) != root.Confidence ||
					got.OnsetUnknown != root.OnsetUnknown {
					problems = append(problems, fmt.Sprintf("anchor %s candidate[%d] = %+v, want %+v",
						failure.AnchorType, i, got, root))
				}
			}
		}
		var chainTypes []string
		for _, id := range match.KnownChain {
			chainTypes = append(chainTypes, string(g.Get(id).Type))
		}
		if !equalStrings(chainTypes, failure.ChainTypes) {
			problems = append(problems, fmt.Sprintf("anchor %s known chain = %v, want %v",
				failure.AnchorType, chainTypes, failure.ChainTypes))
		}
		for _, missing := range failure.MissingIncludes {
			found := false
			for _, got := range match.MissingEvidence {
				if strings.Contains(got, missing) {
					found = true
					break
				}
			}
			if !found {
				problems = append(problems, fmt.Sprintf("anchor %s missing-evidence does not cite %q",
					failure.AnchorType, missing))
			}
		}
		if !equalStrings(match.Alternatives, failure.Alternatives) {
			problems = append(problems, fmt.Sprintf("anchor %s alternatives = %v, want %v",
				failure.AnchorType, match.Alternatives, failure.Alternatives))
		}
	}
	problems = append(problems, compareCounts("failure", actualfailures, wantfailures)...)

	if got := g.Healthy(); got != expected.GraphHealthy {
		problems = append(problems, fmt.Sprintf("graph_healthy = %v, want %v", got, expected.GraphHealthy))
	}
	return problems
}

func compareCounts[K comparable](label string, actual, expected map[K]int) []string {
	var problems []string
	for key, want := range expected {
		if got := actual[key]; got != want {
			problems = append(problems, fmt.Sprintf("%s %+v count = %d, want %d", label, key, got, want))
		}
	}
	for key, got := range actual {
		if expected[key] == 0 {
			problems = append(problems, fmt.Sprintf("unexpected %s %+v (count %d)", label, key, got))
		}
	}
	return problems
}

// TestPrintCausalExpectations prints draft expectations for review. with
// RUNOPSY_PRINT_CAUSAL_FIXTURES=write it also writes expected.json as an
// unreviewed draft; drafts must be read and corrected before committing.
func TestPrintCausalExpectations(t *testing.T) {
	mode := os.Getenv("RUNOPSY_PRINT_CAUSAL_FIXTURES")
	if mode == "" {
		t.Skip("set RUNOPSY_PRINT_CAUSAL_FIXTURES=1 (print) or write (draft) to inspect fixture expectations")
	}
	for _, fixture := range causalFixtures() {
		inc := loadCausalFixture(t, fixture.Name)
		timeline := BuildTimeline(inc)
		graph := NewGraph(timeline)
		if _, err := NewEngine(Rules(), timeline.Origin).Apply(graph, nil); err != nil {
			t.Fatalf("%s: %v", fixture.Name, err)
		}
		expected := buildExpectation(fixture.Name, fixture.Class, fixture.Notes, fixture.Forbidden, timeline, graph)
		encoded, err := json.MarshalIndent(expected, "", "  ")
		if err != nil {
			t.Fatal(err)
		}
		if mode == "write" {
			path := filepath.Join(fixtureDir(fixture.Name), "expected.json")
			if err := os.WriteFile(path, append(encoded, '\n'), 0644); err != nil {
				t.Fatal(err)
			}
			t.Logf("wrote draft %s", path)
		}
		t.Logf("%s\n%s", fixture.Name, encoded)
	}
}
