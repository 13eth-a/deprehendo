// --- events-mode fixtures: a hand-authored normalized event stream ---

// fixtureEventDen describes one normalized event in fixture-local syntax:
// class and provenance are derived by the harness (classOf / fixture
// provenance), so a fixture file cannot contradict the type vocabulary.
type fixtureEventDen struct {
	Type         string         `json:"type"`
	At           string         `json:"at"`
	Subject      fixtureSubRef  `json:"subject"`
	Data         map[string]any `json:"data,omitempty"`
	Episode      string         `json:"episode,omitempty"`
	OnsetUnknown bool           `json:"onset_unknown,omitempty"`
	PID          int            `json:"pid,omitempty"`
	StartTicks   int64          `json:"start_ticks,omitempty"`
	PPID         int            `json:"ppid,omitempty"`
	PGID         int            `json:"pgid,omitempty"`
}

type fixtureSubRef struct {
	Kind string `json:"kind"`
	ID   string `json:"id"`
}

// fixtureEndpoint resolves one edge endpoint by type plus optional
// subject/timestamp disambiguation, so events-mode fixtures can wire a rule
// edge to the exact event instances they reviewed (two OOM records may share
// a type and even a victim identity).
type fixtureEndpoint struct {
	Type    string `json:"type"`
	Subject string `json:"subject,omitempty"`
	At      string `json:"at,omitempty"`
}

type fixtureInjection struct {
	Rule string          `json:"rule"`
	From fixtureEndpoint `json:"from"`
	To   fixtureEndpoint `json:"to"`
}

type eventsFixtureDen struct {
	Events   []fixtureEventDen  `json:"events"`
	Injected []fixtureInjection `json:"injected"`
}

// loadEventsFixtureDec decodes events.json and normalizes it exactly as the
// bundle path would exit: deterministic order, typed IDs, fixture provenance.
func loadEventsFixtureDec(t *testing.T, name string) eventsFixtureDen {
	t.Helper()
	raw, err := os.ReadFile(filepath.Join(fixtureDir(name), "events.json"))
	if err != nil {
		t.Fatalf("read event-stream fixture: %v", err)
	}
	var den eventsFixtureDen
	if err := json.Unmarshal(raw, &den); err != nil {
		t.Fatalf("decode event-stream fixture: %v", err)
	}
	return den
}

func (den eventsFixtureDen) timeline(t *testing.T) (*Timeline, *Graph) {
	t.Helper()
	events := make([]Event, 0, len(den.Events))
	for i, d := range den.Events {
		at, err := time.Parse(time.RFC3339Nano, d.At)
		if err != nil {
			t.Fatalf("event[%d] (%s): bad at %q: %v", i, d.Type, d.At, err)
		}
		e := Event{
			Type:      EventType(d.Type),
			Timestamp: at,
			Subject:   SubjectRef{SubjectKind(d.Subject.Kind), d.Subject.ID},
			Data:      d.Data,
			Episode:   d.Episode,
			PID:       d.PID, StartTicks: d.StartTicks, PPID: d.PPID, PGID: d.PGID,
			OnsetUnknown: d.OnsetUnknown,
			Provenance: EventProvenance{Sources: []ProvenanceSource{
				provenance("events-fixture", fmt.Sprintf("%d", i)),
			}},
		}
		e.Class = classOf(e.Type)
		events = append(events, e)
	}
	sortEvents(events)
	assignIDs(events)
	for i := range events {
		events[i].Sequence = uint64(i)
	}
	if len(events) == 0 {
		t.Fatalf("events.json carries no events")
	}
	tl := &Timeline{Events: events, Origin: events[0].Timestamp}
	g := NewGraph(tl)
	if _, err := NewEngine(Rules(), tl.Origin).Apply(g, nil); err != nil {
		t.Fatalf("apply rules: %v", err)
	}
	for _, injection := range den.Injected {
		injectRuleEdge(t, g, injection)
	}
	// injections can form same-target competing CAUSES pairs the Apply-time
	// D3 pass could not see yet. the pass is idempotent, so re-running it
	// here gives injected edges the same demotion contract as edges apply
	// itself discovered. the audited hypothesis must not be held to a
	// weaker contract than production ingestion.
	markCompetingEdges(g)
	if err := g.Validate(); err != nil {
		t.Fatalf("event-stream fixture graph invalid (injections must stay V3-lawful): %v", err)
	}
	return tl, g
}

// injectRuleEdge wires one declared edge through a real registered rule,
// so injected edges (the audited hypothesis under test) cannot drift from
// the shipped rule vocabulary: endpoints must honor the rule, the band must
// grade to its ceiling, and the recorded checks state the fixture's reviewed
// record facts.
func injectRuleEdge(t *testing.T, g *Graph, injection fixtureInjection) {
	t.Helper()
	var rule *Rule
	for _, r := range Rules() {
		if r.ID == injection.Rule {
			rule = r
		}
	}
	if rule == nil {
		t.Fatalf("injection names unknown rule %q", injection.Rule)
	}
	fromid := resolveEndpoint(t, g, rule, injection.From, "from")
	toid := resolveEndpoint(t, g, rule, injection.To, "to")
	discriminator := map[string]bool{}
	for _, code := range rule.Discriminator {
		discriminator[code] = true
	}
	var checks []CheckRecord
	for _, code := range rule.Required {
		checks = append(checks, CheckRecord{Kind: "required", Code: code, Status: CheckPresent,
			Detail: "present in the reviewed fixture record"})
	}
	for _, code := range rule.Contradicting {
		checks = append(checks, CheckRecord{Kind: "contradicting", Code: code, Status: CheckAbsent,
			Detail: "checked, absent in the reviewed fixture record"})
	}
	p := EdgeProposal{From: fromid, To: toid, Relation: rule.Edge,
		Confidence: capBand(rule.Ceiling, nil), Checks: checks,
		Evidence:  []EvidenceNote{{Code: "FIXTURE_RECORD", Detail: "reviewed fixture fact"}},
		Mechanism: rule.Mechanism}
	p.ruleID = rule.ID
	if err := g.addEdge(p); err != nil {
		t.Fatalf("inject %s: %v", rule.ID, err)
	}
}

func resolveEndpoint(t *testing.T, g *Graph, rule *Rule, ref fixtureEndpoint, side string) EventID {
	t.Helper()
	it := EventType(ref.Type)
	wantsubject := ref.Subject
	wantat := time.Time{}
	if ref.At != "" {
		var err error
		wantat, err = time.Parse(time.RFC3339Nano, ref.At)
		if err != nil {
			t.Fatalf("injection %s.%s: bad at %q: %v", rule.ID, side, ref.At, err)
		}
	}
	switch side {
	case "from":
		if rule.Source != it {
			t.Fatalf("injection %s.from is %s, rule source is %s", rule.ID, it, rule.Source)
		}
	case "to":
		if rule.Target != it {
			t.Fatalf("injection %s.to is %s, rule target is %s", rule.ID, it, rule.Target)
		}
	}
	var found EventID
	for _, id := range g.EventIDs() {
		e := g.Get(id)
		if e.Type != it || (wantsubject != "" && e.Subject.ID != wantsubject) ||
			(!wantat.IsZero() && !e.Timestamp.Equal(wantat)) {
			continue
		}
		if found != "" {
			t.Fatalf("injection %s.%s (%s subject %q at %v) is ambiguous; add subject/at fields", rule.ID, side, it, wantsubject, wantat)
		}
		found = id
	}
	if found == "" {
		t.Fatalf("injection %s.%s: no event matches %s subject %q at %v", rule.ID, side, it, wantsubject, wantat)
	}
	return found
}

func TestWriteCausalFixtures(t *testing.T) {
	mode := os.Getenv("DEPREHENDO_WRITE_CAUSAL_FIXTURES")
	if mode == "" {
		t.Skip("set DEPREHENDO_WRITE_CAUSAL_FIXTURES=create (or force) to write fixture inputs")
	}
	for _, fixture := range causalFixtures() {
		fixture := fixture
		t.Run(fixture.Name, func(t *testing.T) {
			if fixture.Mode == "events" {
				t.Skip("events-mode fixture: its normalized event stream (events.json) is hand-authored reviewed data")
			}
			inc := fixture.Build(t)
			if err := incident.Validate(inc); err != nil {
				t.Fatalf("fixture incident is invalid: %v", err)
			}
			dir := fixtureDir(fixture.Name)
			if err := os.MkdirAll(dir, 0755); err != nil {
				t.Fatal(err)
			}
			path := filepath.Join(dir, "incident.json")
			if _, err := os.Stat(path); err == nil && mode != "force" {
				t.Logf("%s exists; use force to overwrite", path)
				return
			}
			encoded, err := json.MarshalIndent(inc, "", "  ")
			if err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(path, append(encoded, '\n'), 0644); err != nil {
				t.Fatal(err)
			}
			t.Logf("wrote %s", path)
		})
	}
}

